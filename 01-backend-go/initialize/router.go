	system.ApiRouter
	system.JwtRouter
	system.SysRouter
	system.BaseRouter
	system.InitRouter
	system.MenuRouter
	system.UserRouter
	system.CasbinRouter
	system.AutoCodeRouter
	system.AuthorityRouter
	system.DictionaryRouter
	system.OperationRecordRouter
	system.DictionaryDetailRouter
	system.AuthorityBtnRouter
	system.DeviceRouter
